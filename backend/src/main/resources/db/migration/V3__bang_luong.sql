-- V3: Bảng lương nhân viên (UC "Bảng lương nhân viên" — SRS)
-- Kế toán/quản lý xem bảng lương theo tháng, cập nhật hệ số, phụ cấp, thưởng, khấu trừ.

CREATE TABLE bang_luong (

    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    thang           INT          NOT NULL,
    nam             INT          NOT NULL,
    luong_co_ban    DECIMAL(12,2) NOT NULL DEFAULT 0,
    he_so           DECIMAL(5,2) NOT NULL DEFAULT 1.0,
    phu_cap         DECIMAL(12,2) NOT NULL DEFAULT 0,
    thuong          DECIMAL(12,2) NOT NULL DEFAULT 0,
    khau_tru        DECIMAL(12,2) NOT NULL DEFAULT 0,
    ghi_chu         VARCHAR(500) NULL,
    trang_thai      VARCHAR(20)  NOT NULL DEFAULT 'NHAP',
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bang_luong_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_bang_luong_user_thang UNIQUE (user_id, thang, nam)
);
CREATE INDEX idx_bang_luong_thang ON bang_luong (nam, thang);
CREATE OR REPLACE FUNCTION set_updated_at_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER bang_luong_set_updated_at BEFORE UPDATE ON bang_luong FOR EACH ROW EXECUTE FUNCTION set_updated_at_timestamp();