CREATE TABLE promotions (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  type VARCHAR(50) NOT NULL,
  discount_value DECIMAL(15,2) NOT NULL,
  max_discount_amount DECIMAL(15,2),
  start_date TIMESTAMP NOT NULL,
  end_date TIMESTAMP NOT NULL,
  min_order_amount DECIMAL(15,2) DEFAULT 0,
  apply_to_all_products BOOLEAN DEFAULT TRUE,
  usage_limit INT,
  usage_count INT DEFAULT 0,
  status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
  created_by BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_promotion_dates CHECK (end_date > start_date),
  CONSTRAINT chk_promotion_discount_value CHECK (discount_value >= 0),
  CONSTRAINT chk_promotion_usage_count CHECK (usage_count >= 0)
);
CREATE INDEX idx_code ON promotions (code);
CREATE INDEX idx_status ON promotions (status);
CREATE INDEX idx_dates ON promotions (start_date, end_date);
CREATE INDEX idx_type ON promotions (type);

CREATE TABLE promotion_products (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
